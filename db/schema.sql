-- skema database undangan (Supabase / PostgreSQL)
-- jalankan di SQL Editor Supabase

create table if not exists public.guests (
  id        bigint generated by default as identity primary key,
  nama      text not null,
  gelar     text default '',
  asal      text default '',
  kategori  text default 'Tamu',
  whatsapp  text default '',
  dibuat    timestamptz default now()
);

-- tabel konfirmasi
create table if not exists public.rsvp (
  id        bigint generated by default as identity primary key,
  nama      text not null,
  asal      text default '',
  kategori  text default '',
  kehadiran text not null default 'Hadir',
  jumlah    int  not null default 1,
  pesan     text default '',
  waktu     timestamptz default now()
);

-- aktifkan keamanan baris
alter table public.guests enable row level security;
alter table public.rsvp   enable row level security;

-- izin untuk pengunjung
drop policy if exists "guests dibaca tamu"  on public.guests;
create policy "guests dibaca tamu"
  on public.guests for select to anon using (true);

drop policy if exists "rsvp dibaca tamu"    on public.rsvp;
create policy "rsvp dibaca tamu"
  on public.rsvp for select to anon using (true);

drop policy if exists "rsvp ditambah tamu"  on public.rsvp;
create policy "rsvp ditambah tamu"
  on public.rsvp for insert to anon with check (true);

grant usage on schema public to anon;
grant select on public.guests to anon;
grant select, insert on public.rsvp to anon;
grant usage, select on sequence public.rsvp_id_seq to anon;

